#!/usr/bin/env node
// Setup wizard: run once after downloading the repo.
//   macOS: double-click "Setup.command"      Anywhere: npm run setup
// It checks your machine, installs what's needed, prepares the settings file, optionally connects Figma,
// then opens the Design Studio, which finishes setup in the browser (Owner account, API key, Figma token).
// It never asks for or stores keys in the terminal; those go in the studio.
import { execSync, spawn, spawnSync } from 'node:child_process'
import crypto from 'node:crypto'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import readline from 'node:readline/promises'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const studio = path.join(root, 'apps/studio')
const site = path.join(root, 'apps/live-site')
const rl = readline.createInterface({ input: process.stdin, output: process.stdout })
const ok = (s) => console.log(`  ✓ ${s}`)
const warn = (s) => console.log(`  ! ${s}`)
const step = (n, s) => console.log(`\n  ${n}. ${s}\n  ${'─'.repeat(s.length + 3)}`)
const ask = async (q, def = 'y') => {
  const a = (await rl.question(`  ${q} ${def === 'y' ? '[Y/n]' : '[y/N]'} `)).trim().toLowerCase()
  return a ? a.startsWith('y') : def === 'y'
}
const has = (cmd) => spawnSync(process.platform === 'win32' ? 'where' : 'which', [cmd], { stdio: 'ignore' }).status === 0
const npmInstall = (dir) => spawnSync('npm', ['install', '--no-audit', '--no-fund'], { cwd: dir, stdio: 'inherit', shell: process.platform === 'win32' }).status === 0

console.log('\n  Design Agent — setup\n  ====================')
console.log('  About 5 minutes. You can run this again any time; it skips what is already done.')

// 1. Machine
step(1, 'Checking this computer')
const major = Number(process.versions.node.split('.')[0])
if (major < 22) {
  warn(`Node ${process.versions.node} is too old. Install Node 22 or newer (LTS) from https://nodejs.org, then run setup again.`)
  process.exit(1)
}
ok(`Node ${process.versions.node}`)
has('git') ? ok('git') : warn('git not found: you can still run the studio, but pushing changes needs git (https://git-scm.com).')
const chromePaths = ['/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', 'C:/Program Files/Google/Chrome/Application/chrome.exe', '/usr/bin/google-chrome', '/usr/bin/chromium']
if (process.env.STUDIO_CHROME_PATH || chromePaths.some((p) => fs.existsSync(p)) || has('google-chrome')) ok('Google Chrome (the agent takes screenshots with it)')
else warn('Google Chrome not found. Install it from https://www.google.com/chrome, or set STUDIO_CHROME_PATH to another Chromium.')

// 2. Install
step(2, 'Installing the Design Studio')
if (fs.existsSync(path.join(studio, 'node_modules'))) ok('already installed')
else if (!npmInstall(studio)) {
  warn('Install failed. Copy the lines above to Claude or your developer.')
  process.exit(1)
} else ok('installed')

step(3, 'Installing the prototype site (apps/live-site)')
if (fs.existsSync(path.join(site, 'node_modules/next'))) ok('already installed')
else if (await ask('Install it now? It takes a few minutes. (If you skip, the studio installs it the first time it builds a prototype.)')) {
  npmInstall(site) ? ok('installed') : warn('Install failed; the studio will retry when it starts the prototype.')
} else ok('skipped — the studio will install it when needed')

// 4. Settings file
step(4, 'Preparing settings')
const env = path.join(studio, '.env')
if (!fs.existsSync(env)) fs.copyFileSync(path.join(studio, '.env.example'), env)
let text = fs.readFileSync(env, 'utf8')
if (!/^STUDIO_INTAKE_TOKEN=\S+/m.test(text)) {
  const token = crypto.randomBytes(24).toString('base64url')
  text = text.replace(/^#?\s*STUDIO_INTAKE_TOKEN=.*$/m, '') + `\n# Generated by setup: other repos (product BRDs in, dev questions/handover out) send this as "Authorization: Bearer <token>".\nSTUDIO_INTAKE_TOKEN=${token}\n`
  fs.writeFileSync(env, text, { mode: 0o600 })
  ok('apps/studio/.env created, with a private token for other repos (BRD intake, handover, dev questions)')
} else ok('apps/studio/.env already set up')
ok('Keys are NOT asked for here. You add your Anthropic key in the studio (Settings → API keys).')

// 5. Figma
step(5, 'Figma + Mobbin (required)')
console.log('  The studio stays switched off until both are connected: Figma (Lumen library, research, Figma page in every handover)\n  and Mobbin (peer screens; needs a paid Mobbin plan).')
if (await ask('Connect them now? Browser windows open for each sign-in.')) {
  rl.close()
  const sdk = path.join(studio, 'node_modules/@anthropic-ai')
  const dir = fs.existsSync(sdk) ? fs.readdirSync(sdk).find((d) => d.startsWith('claude-agent-sdk-') && fs.existsSync(path.join(sdk, d, 'claude'))) : null
  if (!dir) warn('Claude Code program not found in the studio install. Run "Connect Tools.command" later.')
  else {
    const cli = path.join(sdk, dir, 'claude')
    spawnSync(cli, ['mcp', 'add', '--scope', 'user', '--transport', 'http', 'figma', 'https://mcp.figma.com/mcp'], { stdio: 'inherit', cwd: root })
    spawnSync(cli, ['mcp', 'add', '--scope', 'user', '--transport', 'http', 'mobbin', 'https://api.mobbin.com/mcp'], { stdio: 'inherit', cwd: root })
    console.log('\n  In the window that opens: type  /mcp  → figma → Authenticate (sign in, Allow); then  /mcp  → mobbin → Authenticate; then  /exit\n')
    spawnSync(cli, [], { stdio: 'inherit', cwd: root })
    const list = spawnSync(cli, ['mcp', 'list'], { encoding: 'utf8', cwd: root }).stdout || ''
    for (const t of ['figma', 'mobbin']) new RegExp(`^${t}.*(✓|connected)`, 'im').test(list) ? ok(`${t} connected`) : warn(`${t} not connected yet. Run "Connect Tools.command" any time.`)
  }
} else {
  rl.close()
  ok('skipped — run "Connect Tools.command" before using the studio (it stays off until then)')
}

// 6. Check
step(6, 'Checking the skills')
spawnSync(process.execPath, [path.join(root, 'scripts/skills.mjs'), 'check'], { stdio: 'inherit' })

// 7. Start
step(7, 'Opening the Design Studio')
console.log(`  In the browser:
    1. Create the Owner account (you).
    2. Settings → API keys: paste your Anthropic key (console.anthropic.com → API keys).
    3. Settings → Figma research folder: paste a read-only Figma token.
    4. Home → Check again. The agent stays OFF until key, Figma, Mobbin, research token and Chrome all work.
    5. Settings → People: add your team.
  To start it again later: "Start Design Studio.command" or  npm run studio
`)
const opener = process.platform === 'darwin' ? 'open' : process.platform === 'win32' ? 'start' : 'xdg-open'
setTimeout(() => {
  try {
    execSync(`${opener} http://localhost:4100`, { stdio: 'ignore' })
  } catch {}
}, 2500)
spawn('npm', ['start'], { cwd: studio, stdio: 'inherit', shell: process.platform === 'win32' })
